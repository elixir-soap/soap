defmodule Soap.Generator do
  @moduledoc """
  Generates a client module from a service: one documented, typed function per operation,
  and a type for each complex type those operations use.

  Use it through `mix soap.gen`.
  """

  alias Soap.Schema.{ComplexType, SimpleType, Walk}
  alias Soap.Service

  @kernel_names (Kernel.__info__(:functions) ++ Kernel.__info__(:macros))
                |> Keyword.keys()
                |> MapSet.new(&Atom.to_string/1)
  @reserved ~w(client call def do end fn nil true false when and or not in after else catch rescue) |> MapSet.new()

  @integers ~w(int integer long short byte unsignedInt unsignedLong unsignedShort unsignedByte
               positiveInteger negativeInteger nonPositiveInteger nonNegativeInteger)

  @doc """
  Returns the source of a module named `module` for `service`.

  `source` is the WSDL path or URL the generated `client/1` loads. Generated code doesn't
  embed the WSDL, so the service can move without regenerating.
  """
  @spec generate(Service.t(), String.t(), String.t()) :: String.t()
  def generate(%Service{} = service, module, source) do
    operations = service.operations |> Enum.uniq_by(& &1.name) |> Enum.sort_by(& &1.name)
    names = function_names(operations)
    types = collect_types(service, operations)

    """
    defmodule #{module} do
      @moduledoc \"\"\"
      A client for the SOAP service at `#{source}`.

      Generated by `mix soap.gen`. Regenerate it instead of editing it.

          {:ok, client} = #{module}.client()
          #{module}.#{example_call(names)}
      \"\"\"

      #{Enum.map_join(types, "\n\n", &type_definition(&1, service))}

      @doc "Loads the service. Takes the options of `Soap.load/2`."
      @spec client(keyword()) :: {:ok, Soap.Client.t()} | {:error, Soap.Error.t()}
      def client(opts \\\\ []), do: Soap.load(#{inspect(source)}, opts)

      #{Enum.map_join(operations, "\n\n", &operation_function(&1, names, service))}
    end
    """
    |> Code.format_string!(line_length: 100)
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp example_call([]), do: "client(opts)"
  defp example_call([{_operation, function} | _]), do: "#{function}(client, %{})"

  # Function names

  defp function_names(operations) do
    {pairs, _used} =
      Enum.map_reduce(operations, MapSet.new(), fn operation, used ->
        name = unique_name(safe_name(operation.name), used)
        {{operation.name, name}, MapSet.put(used, name)}
      end)

    pairs
  end

  defp safe_name(name) do
    underscored = name |> String.replace(~r/[^A-Za-z0-9_]/, "_") |> Macro.underscore()
    prefixed = if underscored =~ ~r/^[a-z_]/, do: underscored, else: "op_" <> underscored

    if MapSet.member?(@kernel_names, prefixed) or MapSet.member?(@reserved, prefixed),
      do: prefixed <> "_call",
      else: prefixed
  end

  defp unique_name(name, used) do
    if MapSet.member?(used, name) do
      2
      |> Stream.iterate(&(&1 + 1))
      |> Enum.find_value(fn n -> if not MapSet.member?(used, "#{name}_#{n}"), do: "#{name}_#{n}" end)
    else
      name
    end
  end

  # Operations

  defp operation_function(operation, names, service) do
    function = names |> List.keyfind(operation.name, 0) |> elem(1)
    input = message_type(operation.input, service)
    output = message_type(operation.output, service)

    """
    @doc \"\"\"
    Calls `#{operation.name}`.
    #{field_docs(operation.input, service)}
    \"\"\"
    @spec #{function}(Soap.Client.t(), #{input}, keyword()) :: {:ok, %{optional(String.t()) => #{output}}} | {:error, Soap.Fault.t() | Soap.Error.t()}
    def #{function}(client, params \\\\ %{}, opts \\\\ []), do: Soap.call(client, #{inspect(operation.name)}, params, opts)
    """
  end

  defp field_docs(message, service) do
    case message_fields(message, service) do
      [] ->
        ""

      fields ->
        lines = Enum.map_join(fields, "\n", fn {name, type} -> "  * `#{inspect(name)}` - `#{type}`" end)
        "\nParams:\n\n#{lines}\n"
    end
  end

  defp message_fields(nil, _service), do: []

  defp message_fields(%{body: {:element, qname}}, service) do
    case element_type(service, qname) do
      %ComplexType{} = type -> complex_fields(type, service)
      _ -> []
    end
  end

  defp message_fields(%{parts: parts}, service) do
    Enum.map(parts, fn part -> {part.name, type_expression(part_type(part, service), service)} end)
  end

  defp complex_fields(type, service) do
    {fields, _} = Walk.fields(service.schema, type)
    Enum.map(fields, &{&1.name, field_type(&1, service)})
  end

  defp field_type(field, service) do
    expression = type_expression(Walk.type_of(service.schema, field), service)
    if field.repeats, do: "[#{expression}]", else: expression
  end

  defp message_type(nil, _service), do: "map()"

  defp message_type(%{body: {:element, qname}}, service) do
    type_expression(element_type(service, qname), service)
  end

  defp message_type(_message, _service), do: "map()"

  defp element_type(service, qname) do
    case Walk.find_element(service.schema, qname) do
      nil -> nil
      decl -> Walk.type_of(service.schema, decl)
    end
  end

  defp part_type(%{element: {_, _} = qname}, service), do: element_type(service, qname)
  defp part_type(%{type: type}, service), do: Walk.resolve(service.schema, type)

  # Types

  defp collect_types(service, operations) do
    roots =
      Enum.flat_map(operations, fn operation ->
        Enum.flat_map([operation.input, operation.output], &message_roots(&1, service))
      end)

    roots
    |> Enum.reduce(%{}, &walk_type(&1, &2, service))
    |> Map.values()
    |> Enum.sort_by(&type_name/1)
  end

  defp message_roots(nil, _service), do: []
  defp message_roots(%{body: {:element, qname}}, service), do: List.wrap(element_type(service, qname))
  defp message_roots(%{parts: parts}, service), do: Enum.flat_map(parts, &List.wrap(part_type(&1, service)))

  defp walk_type(%ComplexType{name: name} = type, acc, service) do
    if name != nil and Map.has_key?(acc, {type.ns, name}) do
      acc
    else
      acc = if name, do: Map.put(acc, {type.ns, name}, type), else: acc
      {fields, _} = Walk.fields(service.schema, type)
      Enum.reduce(fields, acc, fn field, inner -> walk_type(Walk.type_of(service.schema, field), inner, service) end)
    end
  end

  defp walk_type(_other, acc, _service), do: acc

  defp type_name(%ComplexType{name: name}),
    do: name |> String.replace(~r/[^A-Za-z0-9_]/, "_") |> Macro.underscore() |> safe_type_name()

  # Elixir defines these types itself.
  defp safe_type_name(name)
       when name in ~w(map list term any atom binary integer float boolean string number tuple struct pid port),
       do: name <> "_type"

  defp safe_type_name(name), do: if(name =~ ~r/^[a-z_]/, do: name, else: "t_" <> name)

  # Typespecs can't name string keys, so the fields are listed in the type's documentation.
  defp type_definition(%ComplexType{} = type, service) do
    fields =
      type
      |> complex_fields(service)
      |> Enum.map_join("\n", fn {name, expression} -> "  * `#{inspect(name)}` - `#{expression}`" end)

    """
    @typedoc \"\"\"
    The `#{type.name}` schema type.

    #{fields}
    \"\"\"
    @type #{type_name(type)} :: %{optional(String.t()) => term()}
    """
  end

  defp type_expression(nil, _service), do: "term()"
  defp type_expression(%ComplexType{name: nil}, _service), do: "map()"

  defp type_expression(%ComplexType{array_type: item} = type, service) when not is_nil(item),
    do: "[#{array_item(type, service)}]"

  defp type_expression(%ComplexType{simple_content: true}, _service), do: "term()"
  defp type_expression(%ComplexType{} = type, _service), do: "#{type_name(type)}()"

  defp type_expression(type, service) do
    case Walk.simple_form(service.schema, type) do
      {:atomic, name, simple} -> atomic_expression(name, simple)
      {:list, item} -> "[#{list_item_expression(item)}]"
      _ -> "term()"
    end
  end

  defp array_item(type, service), do: type_expression(Walk.resolve(service.schema, type.array_type), service)

  defp list_item_expression({:atomic, name, simple}), do: atomic_expression(name, simple)
  defp list_item_expression(_item), do: "term()"

  defp atomic_expression(_name, %SimpleType{enumeration: [_ | _]}), do: "String.t()"
  defp atomic_expression(name, _simple) when name in @integers, do: "integer()"

  defp atomic_expression(name, _simple) when name in ["double", "float"],
    do: "float() | :infinity | :negative_infinity | :nan"

  defp atomic_expression("decimal", _simple), do: "number() | String.t() | struct()"
  defp atomic_expression("boolean", _simple), do: "boolean()"
  defp atomic_expression("date", _simple), do: "Date.t() | String.t()"
  defp atomic_expression("time", _simple), do: "Time.t() | String.t()"
  defp atomic_expression("dateTime", _simple), do: "DateTime.t() | NaiveDateTime.t() | String.t()"
  defp atomic_expression("anyType", _simple), do: "term()"
  defp atomic_expression(_name, _simple), do: "String.t()"
end
